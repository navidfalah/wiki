'use strict';

const YAML_START_SPECIAL = new Set('-?*:!&>|@`#"\'%{},[]');
const YAML_INLINE_SPECIAL = new Set(':\n#\'"<>{}[]|&*`');
const YAML_BOOLISH = new Set(['true', 'false', 'null', 'yes', 'no', 'on', 'off', '~']);

const DRAFT_GENERATED_NOTE = '<!-- AUTO-GENERATED DRAFT — written by compiler/synthesizer.js to compiler/temp_output/. Do not edit this file: it is overwritten on every compile and is not the final wiki page. Edit sources under data/raw/ and recompile; the final linked page lives in wiki-app/docs/. -->';
const FINAL_GENERATED_NOTE = '<!-- AUTO-GENERATED — compiled by the LLM Wiki compiler from data/raw/ sources into compiler/temp_output/, then linked here. Edits to this file are overwritten on the next compile: edit sources under data/raw/, or manual cross-links in data/link_overrides.json, instead. -->';
const GENERATED_BANNER_RE = /^<!--\s*AUTO-GENERATED(?:\sDRAFT)?\b.*?-->\n+/s;

function stripGeneratedBanner(body) {
  return String(body).replace(GENERATED_BANNER_RE, '');
}

function insertGeneratedBanner(content, note) {
  if (!content.startsWith('---')) return `${note}\n\n${content}`;
  const first = content.indexOf('---'), second = content.indexOf('---', first + 3);
  if (second < 0) return `${note}\n\n${content}`;
  const fm = content.slice(first + 3, second), body = content.slice(second + 3).replace(/^\n+/, '');
  return `---${fm}---\n\n${note}\n\n${body}`;
}

function needsYamlQuotes(value) {
  const stripped = value.trimStart();
  if (!stripped || YAML_START_SPECIAL.has(stripped[0])) return true;
  if (value !== value.trim()) return true;
  for (const char of value) if (YAML_INLINE_SPECIAL.has(char)) return true;
  if (YAML_BOOLISH.has(stripped.toLowerCase())) return true;
  return /^[+-]?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?$/.test(stripped);
}

function yamlQuote(value) {
  const text = String(value);
  if (!text) return '""';
  return needsYamlQuotes(text) ? JSON.stringify(text) : text;
}

module.exports = { DRAFT_GENERATED_NOTE, FINAL_GENERATED_NOTE, stripGeneratedBanner, insertGeneratedBanner, yamlQuote };
