"""Formal retrieval evaluation: Recall@5 / nDCG@5 for each retrieval tier,
against retrieval_eval_dataset.py's hand-labeled queries.

Two tiers are always computable, no API key needed:

- `legacy_tfidf_rank` — the exact scoring formula rag_engine.py originally
  shipped with, before this task replaced it. Kept here, isolated and
  clearly labeled, purely as a comparison baseline — nowhere else in the
  codebase uses it anymore.
- `hybrid_retrieval.bm25_rank` — the new default (see rag_engine.retrieve()).

Two more require OPENAI_API_KEY, same "not run automatically, honest about
it when missing" pattern as extraction_critic_eval.py:

- hybrid (BM25 + embeddings via reciprocal rank fusion)
- hybrid + LLM rerank

Run `python retrieval_eval.py` for a formatted report; the BM25-vs-legacy
numbers in documentation/25-hybrid-retrieval.md were generated by this
exact script (that comparison needs no API key, so those numbers are real,
not aspirational).
"""

from __future__ import annotations

import math
from dataclasses import dataclass

import hybrid_retrieval
from llm_client import LLMClient
from retrieval_eval_dataset import QUERIES, RetrievalQuery, build_passage_docs


def legacy_tfidf_rank(query: str, documents: list[hybrid_retrieval.Doc], *, top_k: int = 5) -> list[str]:
    """The original rag_engine.py scorer, verbatim, preserved only as a
    baseline for this evaluation. See git history / documentation/25 for
    context — this is not used anywhere else."""
    query_terms = set(hybrid_retrieval.tokenize(query))
    if not query_terms or not documents:
        return []

    df: dict[str, int] = {}
    for doc in documents:
        for token in set(doc.tokens):
            df[token] = df.get(token, 0) + 1
    n_docs = len(documents)

    scored: list[tuple[str, float]] = []
    for doc in documents:
        if not doc.tokens:
            continue
        term_counts: dict[str, int] = {}
        for token in doc.tokens:
            term_counts[token] = term_counts.get(token, 0) + 1

        score = 0.0
        for term in query_terms:
            tf = term_counts.get(term, 0)
            if tf == 0:
                continue
            idf = math.log((n_docs + 1) / (df.get(term, 0) + 1)) + 1
            score += (tf / len(doc.tokens)) * idf

        if score > 0:
            scored.append((doc.id, score))

    scored.sort(key=lambda item: item[1], reverse=True)
    return [doc_id for doc_id, _ in scored[:top_k]]


def recall_at_k(ranked_ids: list[str], relevant_ids: frozenset[str], k: int) -> float:
    if not relevant_ids:
        return float("nan")
    top_k = set(ranked_ids[:k])
    return len(top_k & relevant_ids) / len(relevant_ids)


def _dcg_at_k(ranked_ids: list[str], relevant_ids: frozenset[str], k: int) -> float:
    dcg = 0.0
    for i, doc_id in enumerate(ranked_ids[:k], start=1):
        if doc_id in relevant_ids:
            dcg += 1.0 / math.log2(i + 1)
    return dcg


def ndcg_at_k(ranked_ids: list[str], relevant_ids: frozenset[str], k: int) -> float:
    """Binary relevance nDCG: the ideal ranking is any ordering with all
    relevant docs in the first min(k, |relevant|) positions."""
    if not relevant_ids:
        return float("nan")
    dcg = _dcg_at_k(ranked_ids, relevant_ids, k)
    ideal_hits = min(k, len(relevant_ids))
    idcg = sum(1.0 / math.log2(i + 1) for i in range(1, ideal_hits + 1))
    return dcg / idcg if idcg > 0 else float("nan")


@dataclass(frozen=True)
class TierReport:
    name: str
    mean_recall_at_5: float
    mean_ndcg_at_5: float


def _evaluate_rank_fn(name: str, rank_fn, queries: list[RetrievalQuery], k: int = 5) -> TierReport:
    recalls = []
    ndcgs = []
    for query in queries:
        ranked_ids = rank_fn(query.text)
        recalls.append(recall_at_k(ranked_ids, query.relevant_ids, k))
        ndcgs.append(ndcg_at_k(ranked_ids, query.relevant_ids, k))
    return TierReport(name, sum(recalls) / len(recalls), sum(ndcgs) / len(ndcgs))


def evaluate_no_api_tiers(k: int = 5) -> list[TierReport]:
    """legacy TF-IDF vs. BM25 — the comparison that needs no API key."""
    docs = build_passage_docs()

    def legacy(query_text: str) -> list[str]:
        return legacy_tfidf_rank(query_text, docs, top_k=k)

    def bm25(query_text: str) -> list[str]:
        return [r.doc_id for r in hybrid_retrieval.bm25_rank(query_text, docs, top_k=k)]

    return [
        _evaluate_rank_fn("legacy_tfidf", legacy, QUERIES, k),
        _evaluate_rank_fn("bm25", bm25, QUERIES, k),
    ]


def evaluate_hybrid_tiers(llm: LLMClient, k: int = 5) -> list[TierReport]:
    """Hybrid (BM25+embeddings via RRF) and hybrid+rerank — requires a
    live LLM/embeddings API."""
    docs = build_passage_docs()
    shortlist_k = max(k * 3, k)

    def hybrid(query_text: str) -> list[str]:
        bm25_top = hybrid_retrieval.bm25_rank(query_text, docs, top_k=shortlist_k)
        embedding_top = hybrid_retrieval.embedding_rank(query_text, docs, llm.embed_text, top_k=shortlist_k)
        fused = hybrid_retrieval.reciprocal_rank_fusion([bm25_top, embedding_top], top_k=shortlist_k)
        return [r.doc_id for r in fused[:k]]

    def hybrid_reranked(query_text: str) -> list[str]:
        bm25_top = hybrid_retrieval.bm25_rank(query_text, docs, top_k=shortlist_k)
        embedding_top = hybrid_retrieval.embedding_rank(query_text, docs, llm.embed_text, top_k=shortlist_k)
        fused = hybrid_retrieval.reciprocal_rank_fusion([bm25_top, embedding_top], top_k=shortlist_k)
        docs_by_id = {d.id: d for d in docs}
        candidates = [docs_by_id[r.doc_id] for r in fused[: k * 2] if r.doc_id in docs_by_id]
        reranked = hybrid_retrieval.llm_rerank(query_text, candidates, llm, top_n=k)
        return [r.doc_id for r in reranked]

    return [
        _evaluate_rank_fn("hybrid_bm25_embeddings", hybrid, QUERIES, k),
        _evaluate_rank_fn("hybrid_reranked", hybrid_reranked, QUERIES, k),
    ]


def _print_report(report: TierReport) -> None:
    print(f"{report.name:28s} recall@5={report.mean_recall_at_5:.2f}  ndcg@5={report.mean_ndcg_at_5:.2f}")


if __name__ == "__main__":
    print("=== No-API tiers (legacy TF-IDF vs BM25) ===")
    for report in evaluate_no_api_tiers():
        _print_report(report)

    client = LLMClient()
    if client.available:
        print("\n=== Hybrid tiers (embeddings + reranker) ===")
        for report in evaluate_hybrid_tiers(client):
            _print_report(report)
    else:
        print(
            "\nNo OPENAI_API_KEY configured (.env) — skipping the hybrid/reranked tiers. "
            "The BM25-vs-legacy comparison above needs no key; the embeddings and "
            "reranker tiers do."
        )
